# GF(2^8) decode
function gf-dec {
    param([byte[]]$d, [byte]$k)
    $r = New-Object byte[] $d.Length
    for($i=0;$i -lt $d.Length;$i++){
        $m = [byte](([byte]($k * (($i % 255) + 1))) -bxor 0xA5)
        $r[$i] = $d[$i] -bxor $m
    }
    return $r
}

